            '＜銀行振込（先払い）について＞',
            '下記の振込先へお振込みください。',
            '',
            '商品代金＋送料の振込みをお願いいたします。',
            '7日以内にお振込みください。',
            '入金確認後に商品の発送をいたします。',
            '',
            '＜'.$shopName.'振込先＞',
